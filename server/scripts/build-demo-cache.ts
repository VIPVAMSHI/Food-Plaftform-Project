import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { NEIGHBORHOODS } from '../../src/data/places.js'
import { AssistantCache } from '../src/assistant/cache.js'
import { PREWARM_QUERIES } from '../src/assistant/demoQueries.js'
import { AssistantService } from '../src/assistant/service.js'
import { loadEnv } from '../src/env.js'
import { googleProvider } from '../src/llm/google.js'
import { LlmKeyStore } from '../src/llm/keyStore.js'
import { RateLimiter } from '../src/rateLimit.js'

/**
 * Asks the live model the demo queries and writes the answers to server/src/assistant/demoCache.ts,
 * which is committed and bundled read-only with the server. Needs LLM_API_KEY and LLM_MODEL (server/.env or the shell).
 * Without a key it writes an empty cache: local answers are computed live and need no cache.
 *   npm run cache:build
 */
const OUT = resolve(import.meta.dirname, '../src/assistant/demoCache.ts')

const env = loadEnv()
const cache = new AssistantCache(null, 500)
let model: string | null = null
if (env.LLM_API_KEY && env.LLM_MODEL) {
  model = env.LLM_MODEL
  const service = new AssistantService({
    provider: googleProvider(new LlmKeyStore(env.LLM_API_KEY, null), env.LLM_MODEL),
    cache,
    llmLimiter: new RateLimiter(1000, 60_000),
    neighborhoods: [...NEIGHBORHOODS],
    log: { info: () => undefined, warn: () => undefined },
  })
  const counts = await service.prewarm(PREWARM_QUERIES)
  console.log(`Model ${model}: ${counts.llm} live answers, ${counts.local} fell back to the local matcher.`)
} else {
  console.log('No LLM_API_KEY/LLM_MODEL: writing an empty demo cache (answers are computed live by the local matcher).')
}

const data = { version: 1, generatedAt: model ? new Date().toISOString() : null, model, entries: cache.llmEntries().entries }
writeFileSync(
  OUT,
  `// Generated by \`npm run cache:build\`. Do not edit by hand.
// Live-model answers for the demo queries, bundled read-only with the server so the demo still gets model-quality
// answers when the model is slow or down. Empty when it was generated without an LLM key (local answers are computed live).
export const DEMO_CACHE = ${JSON.stringify(data, null, 2)} as const
`,
)
console.log(`Wrote ${Object.keys(data.entries).length} entries to ${OUT}`)
